/** Markdown → 單行純文字（卡片摘要用）；只求可讀，不求完整語法 */
export const plainText = (md: string) =>
	md
		.replace(/```[\s\S]*?(```|$)/g, ' ')
		.replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
		.replace(/\[([^\]]*(?:\[[^\]]*\][^\]]*)*)\]\([^)]*\)/g, '$1')
		.replace(/<[^>]+>/g, ' ')
		.replace(/^\s{0,3}(#{1,6}|>|[-*+]|\d+\.)\s+/gm, '')
		.replace(/(\*\*|__|~~|\*|`)(.+?)\1/g, '$2')
		.replace(/\s+/g, ' ')
		.trim();
